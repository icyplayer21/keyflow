#!/usr/bin/env python3
"""Embeds Assets/Hands/*.svg into the app as Swift string literals.

The app reads and parses this SVG text at runtime, so the SVG files stay the
single source of truth without needing a resource bundle inside Keyflow.app.
Run after editing either SVG; a unit test fails if the embedded copy differs.

Usage: python3 Scripts/hand-artwork/embed_hands.py
"""
import os

root = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
source = os.path.join(root, "Assets", "Hands")
target = os.path.join(root, "Sources", "Keyflow", "Design", "HandArtwork", "HandArtworkSources.swift")


def literal(text):
    assert '"""#' not in text
    # A multi-line literal drops the newline before its closing delimiter: add one back.
    return '#"""\n' + text + '\n"""#'


left = open(os.path.join(source, "left-hand.svg")).read()
right = open(os.path.join(source, "right-hand.svg")).read()
swift = f"""// Generated by Scripts/hand-artwork/embed_hands.py from Assets/Hands. Do not edit.
// Edit the SVG files, then run the script again.

enum HandArtworkSources {{
    static let left = {literal(left)}

    static let right = {literal(right)}
}}
"""
with open(target, "w") as f:
    f.write(swift)
print("Wrote", os.path.relpath(target, root))
